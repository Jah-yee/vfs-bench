#!/usr/bin/env python
import argparse
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
# The dataset seam, not a spelled path: these used to live inside
# `task/toolathlon/` and hardcode it, which is the one thing the seam
# exists to stop.
sys.path.insert(0, str(REPO_ROOT / "agent"))
import dataset  # noqa: E402

DEFAULT_ENDPOINT = "http://127.0.0.1:9051"


def endpoint() -> str:
    """Where the emulator is listening.

    Returns:
        str: the base URL, with no trailing slash.
    """
    return os.environ.get("BQ_ENDPOINT", DEFAULT_ENDPOINT).rstrip("/")


def call(path: str, method: str = "GET") -> dict:
    """One request against the emulator's REST API.

    No credentials: the emulator does not check them, which is why this
    talks to it directly rather than through `google-cloud-bigquery` and
    the token stub.

    Args:
        path (str): everything after the base URL, leading slash included.
        method (str): the HTTP method.

    Returns:
        dict: the parsed response, or `{}` for an empty body.

    Raises:
        SystemExit: the emulator refused or could not be reached.
    """
    request = urllib.request.Request(f"{endpoint()}{path}", method=method)
    try:
        with urllib.request.urlopen(request, timeout=60) as reply:
            body = reply.read()
    except urllib.error.HTTPError as failure:
        detail = failure.read().decode(errors="replace").strip()
        sys.exit(f"reset_bigquery: {method} {path}: {detail or failure.code}")
    except urllib.error.URLError as failure:
        sys.exit(f"reset_bigquery: cannot reach {endpoint()}: "
                 f"{failure.reason}")
    return json.loads(body) if body else {}


def sweep(task: str) -> int:
    """Drop every table in the task's datasets that the manifest does not name.

    Args:
        task (str): the task name.

    Returns:
        int: how many tables were dropped.

    Raises:
        SystemExit: the fixture is generated by upstream's preprocess, so
            there is no committed table list to sweep back to.
    """
    path = dataset.local(task) / "shared" / "bigquery.json"
    manifest = json.loads(path.read_text(encoding="utf-8"))
    if manifest.get("preprocess"):
        raise SystemExit(
            f"reset_bigquery: {task}'s fixture is generated by "
            f"{manifest['preprocess']}, so there is no committed "
            f"list of fixture tables to keep; restart "
            f"uv run python server/fakes/gcp.py to rebuild the dataset")

    project = manifest["project"]
    keep: dict[str, set[str]] = {}
    for table in manifest["tables"]:
        keep.setdefault(table["dataset"], set()).add(table["table"])

    dropped = 0
    # `bq_dataset`, not `dataset`: this module imports the seam under that
    # name, and a loop binding would make it local to the whole function --
    # which is how `dataset.local(task)` above raised UnboundLocalError.
    for bq_dataset, wanted in keep.items():
        listing = call(f"/bigquery/v2/projects/{urllib.parse.quote(project)}"
                       f"/datasets/{urllib.parse.quote(bq_dataset)}/tables")
        for entry in listing.get("tables", []):
            name = entry["tableReference"]["tableId"]
            if name in wanted:
                continue
            call(
                f"/bigquery/v2/projects/{urllib.parse.quote(project)}"
                f"/datasets/{urllib.parse.quote(bq_dataset)}/tables/"
                f"{urllib.parse.quote(name)}",
                method="DELETE")
            print(f"bq: dropped {bq_dataset}.{name}")
            dropped += 1
    print(f"bq: {task} reset, {dropped} table(s) dropped")
    return dropped


def main() -> int:
    """Sweep one task's datasets from the command line.

    Returns:
        int: process exit status.
    """
    parser = argparse.ArgumentParser()
    parser.add_argument("task")
    sweep(parser.parse_args().task)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

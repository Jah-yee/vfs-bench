def code_only(query: str) -> str:
    """The query with its string literals and comments blanked out.

    Args:
        query (str): the SQL as the caller wrote it.

    Returns:
        str: the same length of text, with anything opaque replaced by
            spaces, so offsets still line up and no pattern can match into
            a literal.
    """
    return OPAQUE.sub(lambda m: m[0] if m["name"] else " " * len(m[0]), query)


def database_in(query: str) -> str | None:
    """Which database a query is written against, if it says.

    Args:
        query (str): the SQL as the caller wrote it.

    Returns:
        str | None: the database name, or None when the query names none.
    """
    query = code_only(query)
    column = COMMENT_ON_COLUMN.match(query)
    if column:
        parts = re.findall(NAME_PART, column.group(1))
        return parts[0].strip('"').lower() if len(parts) == 4 else None
    schema = CREATE_SCHEMA_DB.match(query)
    if schema:
        return schema.group(1).lower()
    for pattern in (INFORMATION_SCHEMA_OF, QUALIFIED):
        for found in pattern.finditer(query):
            name = found.group(1).strip('"').lower()
            if name not in NOT_A_DATABASE:
                return name
    return None


def used(query: str) -> tuple[str | None, str | None] | None:
    """The database and schema a `USE` statement makes current.

    Args:
        query (str): the SQL as the caller wrote it.

    Returns:
        tuple[str | None, str | None] | None: the database, None when the
            statement keeps the one in use, and the schema, None when it
            names only a database; each as Snowflake would resolve the
            name. None for any other statement.
    """
    found = USE_OBJECT.match(code_only(query))
    if not found:
        return None
    kind = (found["kind"] or "").upper()
    first, second = (None if part is None else
                     part[1:-1] if part.startswith('"') else part.upper()
                     for part in (found["first"], found["second"]))
    if second is not None:
        return None if kind == "DATABASE" else (first, second)
    return (None, first) if kind == "SCHEMA" else (first, None)


def postgres_name(name: str) -> str:
    """Where Postgres keeps a name Snowflake has resolved.

    Args:
        name (str): the name, as `used` resolved it.

    Returns:
        str: folded down unless it is mixed case, as `fold_identifier`
            sends it.
    """
    return name if any(c.islower() for c in name) else name.lower()


def use(database: str, schema: str | None) -> None:
    """Check that a `USE` names a database, and a schema, that exist.

    Args:
        database (str): the database the session would be in.
        schema (str | None): the schema, or None to check only the
            database.

    Raises:
        LookupError: either is missing, with Snowflake's message.
    """
    target = database.lower()
    if target == ACCOUNT_METADATA_DB:
        target = MAINTENANCE_DB
    conn = psycopg2.connect(database=MAINTENANCE_DB, **dsn_parts())
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT 1 FROM pg_database WHERE datname = %s",
                        (target, ))
            if cur.fetchone() is None:
                raise LookupError(MISSING_OBJECT)
    finally:
        conn.close()
    if schema is None:
        return
    # SNOWFLAKE's schemas are Snowflake's own -- ACCOUNT_USAGE, CORE and
    # the rest -- and PUBLIC is not among them; the `public` the
    # maintenance database has is Postgres's.
    if database.lower() == ACCOUNT_METADATA_DB and \
            postgres_name(schema) == "public":
        raise LookupError(MISSING_OBJECT)
    conn = psycopg2.connect(database=target, **dsn_parts())
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT 1 FROM pg_namespace WHERE nspname = %s",
                        (postgres_name(schema), ))
            if cur.fetchone() is None:
                raise LookupError(MISSING_OBJECT)
    finally:
        conn.close()


def fold_identifier(found: re.Match) -> str:
    """Send a quoted upper-case identifier where the unquoted one goes.

    Args:
        found (re.Match): a double-quoted identifier.

    Returns:
        str: the identifier, folded down unless it was already mixed case.
    """
    name = found.group(1)
    return f'"{name.lower()}"' if not any(c.islower() for c in name) else \
        found.group(0)


def rewrite_sql(fragment: str, ddl: bool) -> str:
    """Apply every dialect rule to one run of actual SQL.

    Args:
        fragment (str): SQL with no string literals or comments in it.
        ddl (bool): whether the statement is a CREATE or an ALTER, which
            is the only place type names are rewritten.

    Returns:
        str: the Postgres spelling.
    """
    fragment = DATABASES_QUERY.sub(
        lambda m: f"{DATABASES_RELATION} AS {m['alias'] or 'databases'}",
        fragment)
    fragment = CATALOG_VIEW.sub(
        lambda m: f"{CATALOG_VIEWS[m.group(1).lower()]} AS "
        f"{m['alias'] or m.group(1).lower()}", fragment)
    fragment = outside_quotes(fragment, FUNCTIONS)
    if ddl:
        fragment = outside_quotes(fragment, TYPES)
    return QUOTED_IDENTIFIER.sub(fold_identifier, fragment)


def outside_quotes(fragment: str, rules) -> str:
    """Apply `(pattern, replacement)` rules only between quoted identifiers.

    A quoted identifier is a name spelt exactly, so `"CURRENT_DATE()"`
    stays a column rather than becoming a call, and a quoted `"NUMBER"`
    stays a column's name inside a CREATE.

    Args:
        fragment (str): SQL with no string literals or comments in it.
        rules: the `(pattern, replacement)` pairs to apply.

    Returns:
        str: the fragment, rewritten outside its quoted identifiers.
    """
    parts, at = [], 0
    for quoted in QUOTED_IDENTIFIER.finditer(fragment):
        parts += [fragment[at:quoted.start()], quoted.group(0)]
        at = quoted.end()
    parts.append(fragment[at:])
    for index in range(0, len(parts), 2):
        for pattern, replacement in rules:
            parts[index] = pattern.sub(replacement, parts[index])
    return "".join(parts)


def rewrite(query: str, schema: str | None = None) -> str:
    """Turn one Snowflake statement into its Postgres spelling.

    String literals and comments are found first and passed through
    untouched, so a rule can only ever reach code.

    Args:
        query (str): the SQL as the caller wrote it.
        schema (str | None): the session's schema, which makes an
            unqualified view a catalog one when it is INFORMATION_SCHEMA.

    Returns:
        str: the SQL to send to Postgres.
    """
    # A qualified name whose database part is the connection's own database
    # is legal in Postgres as written, so nothing rewrites those.
    # Whole-statement, so nothing else in it needs rewriting -- and the
    # later rules would undo this one, since the alias they would see is a
    # quoted identifier ending in the very parentheses being restored.
    bare = BARE_NOW.match(query)
    if bare:
        name = bare.group(1).upper()
        return f'SELECT {name} AS "{name}()"'
    # First, so an expression it copies into HAVING gets every rule below.
    query = having_aliases(query)
    query = rewrite_dateadd(query)
    query = rewrite_datediff(query)
    comment = COLUMN_COMMENT.match(query)
    if comment:
        query = (f"COMMENT ON COLUMN {comment.group('table')}."
                 f"{comment.group('column')} IS {comment.group('text')}")
    query = SCHEMA_PREFIX.sub(r"\1", query)
    if reads_catalog(query, schema):
        query = fold_catalog_literals(query)
    ddl = bool(DDL_STATEMENT.match(query))
    out, at = [], 0
    for opaque in OPAQUE.finditer(query):
        if opaque["name"]:
            continue
        out.append(rewrite_sql(query[at:opaque.start()], ddl))
        out.append(opaque.group(0))
        at = opaque.end()
    out.append(rewrite_sql(query[at:], ddl))
    return "".join(out)


def reads_catalog(query: str, schema: str | None) -> bool:
    """Whether a statement reads Snowflake's catalog.

    Args:
        query (str): the SQL as the caller wrote it.
        schema (str | None): the session's schema.

    Returns:
        bool: it names INFORMATION_SCHEMA in its code, or runs in it.
    """
    return bool(CATALOG_SCHEMA.search(
        code_only(query))) or (schema or "").lower() == "information_schema"


def fold_catalog_literals(query: str) -> str:
    """Give each literal compared with a catalog column Postgres's case.

    Snowflake keeps an unquoted name upper-cased and Postgres lower-cased,
    so a literal is folded down as `postgres_name` folds a name: a mixed
    case one is left, as `fold_identifier` leaves a quoted name. Only the
    single-quoted strings in code are read; a dollar-quoted string and a
    comment are passed through as written.

    Args:
        query (str): the SQL as the caller wrote it.

    Returns:
        str: the query, with those literals folded.
    """
    code = code_only(query)
    out, at = [], 0
    for literal in OPAQUE.finditer(query):
        if not literal[0].startswith("'"):
            continue
        start, end = literal.span()
        if (CATALOG_BEFORE.search(code, 0, start)
                or CATALOG_AFTER.match(code, end)
                or in_catalog_list(code, start)):
            out += [query[at:start], f"'{postgres_name(literal[0][1:-1])}'"]
            at = end
    out.append(query[at:])
    return "".join(out)


def in_catalog_list(code: str, start: int) -> bool:
    """Whether the literal at `start` is a member of a catalog `IN` list.

    A member, not an argument of a call inside the list, nor a value a
    subquery in its place selects; `NULL` and other members may sit
    beside it.

    Args:
        code (str): the query, as `code_only` blanks it.
        start (int): where the literal opens.

    Returns:
        bool: its innermost open parenthesis is a catalog column's list.
    """
    depth = 0
    for at in range(start - 1, -1, -1):
        if code[at] == ")":
            depth += 1
        elif code[at] == "(":
            if depth == 0:
                return bool(
                    CATALOG_IN.search(code, 0, at)
                    and not SUBQUERY.match(code, at + 1))
            depth -= 1
    return False


def having_aliases(query: str) -> str:
    """Put a select-list alias's expression where HAVING names the alias.

    Each HAVING reads the select list of the SELECT that owns it, at the
    same parenthesis depth. A name inside an aggregate's or GROUPING's
    arguments, or inside a subquery, is left as written: the subquery's
    names are its own, an alias for an aggregate inside another aggregate is
    an error either way, and GROUPING takes a grouping column.

    Args:
        query (str): the SQL as the caller wrote it.

    Returns:
        str: the query, with `(expression)` for each alias a HAVING names.
    """

    def masked(text: str) -> str:
        """The text with literals, comments and quoted names blanked."""
        return QUOTED_IDENTIFIER.sub(lambda m: " " * len(m.group(0)),
                                     code_only(text))

    count = sum(
        m.group(0).upper() == "HAVING" for m in CLAUSE.finditer(masked(query)))
    for index in reversed(range(count)):
        # Re-read after each rewrite, which moves everything after it.
        code, plain = code_only(query), masked(query)
        depth, level = [], 0
        for char in plain:
            level += char == "("
            depth.append(level)
            level -= char == ")"
        clauses = [(m.start(), m.end(), re.sub(r"\s+", " ",
                                               m.group(0).upper()))
                   for m in CLAUSE.finditer(plain)]
        having = [c for c in clauses if c[2] == "HAVING"][index]
        at = depth[having[0]]

        def same_group(start: int, end: int) -> bool:
            """Whether nothing between the two leaves `having`'s parens."""
            return min(depth[start:end + 1], default=at) >= at

        before = [
            c for c in clauses if c[0] < having[0] and depth[c[0]] == at
            and same_group(c[0], having[0])
        ]
        select = next((c for c in reversed(before) if c[2] == "SELECT"), None)
        if not select:
            continue
        # Without a FROM, the select list runs up to the HAVING itself.
        stop = next(
            (c[0] for c in before if c[0] > select[0] and c[2] == "FROM"),
            having[0])
        end = next((c[0] for c in clauses if c[0] > having[0]
                    and depth[c[0]] == at and c[2] not in ("SELECT", "FROM")),
                   len(query))
        end = next((i for i in range(having[1], end) if depth[i] < at), end)
        groups, opened = [], []
        for i in range(having[1], end):
            if plain[i] == "(":
                opened.append(i)
            elif plain[i] == ")" and opened:
                groups.append((opened.pop(), i))
        closed = [
            (left, right) for left, right in groups
            if AGGREGATE.search(plain[having[1]:left]) or re.match(
                r"\s*(SELECT|WITH)\b", plain[left + 1:right], re.IGNORECASE)
        ]
        aliases, start = {}, select[1]
        for i in range(select[1], stop + 1):
            if i < stop and not (plain[i] == "," and depth[i] == at):
                continue
            alias = AS_ALIAS.search(code[start:i])
            if alias:
                name = alias.group(1)
                key = name[1:-1] if name.startswith('"') else name.upper()
                aliases[key] = SELECT_QUANTIFIER.sub(
                    "", query[start:start + alias.start()]).strip()
            start = i + 1
        body = code[having[1]:end]
        for name in reversed(list(BARE_NAME.finditer(body))):
            word = name.group(1)
            key = word[1:-1] if word.startswith('"') else word.upper()
            left, right = having[1] + name.start(), having[1] + name.end()
            if key in aliases and not any(open_ < left and right <= shut
                                          for open_, shut in closed):
                query = f"{query[:left]}({aliases[key]}){query[right:]}"
    return query


def rewrite_dateadd(query: str) -> str:
    """Translate the DATEADD units exercised by the fixture tasks.

    The argument scan follows balanced parentheses so a CASE expression or a
    nested call can contain commas without splitting the outer call. Calls in
    literals, comments and quoted identifiers are masked before scanning.
    """
    masked = QUOTED_IDENTIFIER.sub(lambda m: " " * len(m.group(0)),
                                   code_only(query))
    calls = list(re.finditer(r"\bDATEADD\s*\(", masked, re.IGNORECASE))
    for call in reversed(calls):
        depth, start, parts = 1, call.end(), []
        # Re-mask after replacing an inner call; its length may have changed.
        masked = QUOTED_IDENTIFIER.sub(lambda m: " " * len(m.group(0)),
                                       code_only(query))
        for end in range(start, len(query)):
            char = masked[end]
            if char == "(":
                depth += 1
            elif char == ")":
                depth -= 1
            if (char == "," and depth == 1) or depth == 0:
                parts.append(query[start:end].strip())
                start = end + 1
            if depth == 0:
                break
        if depth or len(parts) != 3:
            continue
        unit = parts[0].lower()
        intervals = {
            "hour": "1 hour",
            "'hour'": "1 hour",
            "day": "1 day",
            "'day'": "1 day",
        }
        if unit not in intervals:
            continue
        amount, timestamp = parts[1:]
        replacement = (f"(({timestamp}) + ({amount}) * "
                       f"INTERVAL '{intervals[unit]}')")
        query = query[:call.start()] + replacement + query[end + 1:]
    return query


def rewrite_datediff(query: str) -> str:
    """Translate the DATEDIFF units exercised by the fixture tasks.

    Snowflake counts boundaries of the requested unit, not rounded elapsed
    time. Leave other units to the backend rather than silently giving a
    wrong answer. Scan balanced SQL, keeping commas in calls, literals and
    comments intact.
    """
    masked = QUOTED_IDENTIFIER.sub(lambda m: " " * len(m.group(0)),
                                   code_only(query))
    calls = list(re.finditer(r"\bDATEDIFF\s*\(", masked, re.IGNORECASE))
    for call in reversed(calls):
        depth, start, parts = 1, call.end(), []
        # Re-mask after replacing an inner call; its length may have changed.
        masked = QUOTED_IDENTIFIER.sub(lambda m: " " * len(m.group(0)),
                                       code_only(query))
        for end in range(start, len(query)):
            char = masked[end]
            if char == "(":
                depth += 1
            elif char == ")":
                depth -= 1
            if (char == "," and depth == 1) or depth == 0:
                parts.append(query[start:end].strip())
                start = end + 1
            if depth == 0:
                break
        if depth or len(parts) != 3:
            continue
        written_unit = parts[0].lower()
        units = {
            spelling: unit
            for unit in ("second", "minute", "hour", "day")
            for spelling in (unit, f"'{unit}'")
        }
        unit = units.get(written_unit)
        seconds = {"second": 1, "minute": 60, "hour": 3600}
        if unit is None:
            continue
        left, right = parts[1:]
        if unit == "day":
            replacement = (
                "CAST(("
                f"DATE_TRUNC('day', ({right})::timestamptz)::date - "
                f"DATE_TRUNC('day', ({left})::timestamptz)::date"
                ") AS BIGINT)")
        else:
            replacement = ("CAST(EXTRACT(EPOCH FROM ("
                           f"DATE_TRUNC('{unit}', ({right})::timestamptz) - "
                           f"DATE_TRUNC('{unit}', ({left})::timestamptz)"
                           f")) / {seconds[unit]} AS BIGINT)")
        query = query[:call.start()] + replacement + query[end + 1:]
    return query


def present(rows: list[dict], catalog: bool) -> list[dict[str, Any]]:
    """Give the rows Snowflake's casing.

    Column names come back upper-cased always; in a read of the catalog
    the values of catalog columns come back as `snowflake_name` gives
    them, because that is the case Snowflake stores identifiers in and a
    caller may compare against it.

    Args:
        rows (list[dict]): rows as psycopg2 produced them.
        catalog (bool): whether the statement read the catalog.

    Returns:
        list[dict[str, Any]]: the same rows, re-cased.
    """
    shown = []
    for row in rows:
        item = {}
        for name, value in row.items():
            if (catalog and name.lower() in CATALOG_COLUMNS
                    and isinstance(value, str)):
                value = snowflake_name(value)
            item[name.upper()] = value
        shown.append(item)
    return shown


def bare_code(query: str) -> str:
    """The query with its literals, comments and quoted names blanked.

    Args:
        query (str): SQL.

    Returns:
        str: the same length of text, so offsets still line up.
    """
    return QUOTED_IDENTIFIER.sub(lambda m: " " * len(m.group(0)),
                                 code_only(query))


def statement_count(query: str) -> int:
    """How many statements Snowflake would count in one call.

    Args:
        query (str): the SQL as the caller wrote it.

    Returns:
        int: the runs of code between semicolons, a trailing semicolon
            opening none.
    """
    return sum(1 for part in bare_code(query).split(";") if part.strip())


def snowflake_name(name: str) -> str:
    """The name Snowflake keeps for one Postgres keeps: `postgres_name`
    the other way round.

    Args:
        name (str): as Postgres's catalog has it.

    Returns:
        str: upper case, unless Postgres has it in mixed case.
    """
    return name if any(c.isupper() for c in name) else name.upper()


def catalog_name(database: str) -> str:
    """The Snowflake database a Postgres one stands in for.

    Args:
        database (str): the Postgres database.

    Returns:
        str: its Snowflake name, SNOWFLAKE for the maintenance database.
    """
    return snowflake_name(ACCOUNT_METADATA_DB if database ==
                          MAINTENANCE_DB else database)


def identifier(name: str) -> str:
    """A Snowflake name as DDL spells it: quoted only where it has to be.

    Args:
        name (str): the name as Snowflake keeps it.

    Returns:
        str: the name, double-quoted unless it reads the same unquoted.
    """
    if PLAIN_NAME.fullmatch(name):
        return name
    return '"' + name.replace('"', '""') + '"'


def literal(text: str) -> str:
    """A string literal.

    Args:
        text (str): the value.

    Returns:
        str: single-quoted, with single quotes doubled.
    """
    return "'" + text.replace("'", "''") + "'"


def object_name(text: str) -> list[str] | None:
    """The parts of a Snowflake object name, as Snowflake resolves each.

    Args:
        text (str): `[<database>.][<schema>.]<object>`, any part quoted.

    Returns:
        list[str] | None: one to three parts, an unquoted one in upper
            case; None when the text is not a name, as an unquoted part
            that starts with a digit is not.
    """
    if not re.fullmatch(rf"\s*{NAME_PART}(?:\s*\.\s*{NAME_PART}){{0,2}}\s*",
                        text):
        return None
    return [
        part[1:-1] if part.startswith('"') else part.upper()
        for part in re.findall(NAME_PART, text)
    ]


def connect(database: str | None, schema: str | None):
    """Open a connection to the database a statement is routed to.

    Args:
        database (str | None): the Postgres database, or the Snowflake
            one it stands in for; None for the maintenance database.
        schema (str | None): the schema an unqualified name resolves in,
            as `used` resolved it; None leaves Postgres's own.

    Returns:
        psycopg2.extensions.connection: autocommitted, and with the schema
            on its search path.
    """
    target = (database or MAINTENANCE_DB).lower()
    if target == ACCOUNT_METADATA_DB:
        target = MAINTENANCE_DB
    conn = psycopg2.connect(database=target, **dsn_parts())
    conn.autocommit = True
    if schema is not None:
        with conn.cursor() as cur:
            cur.execute(
                psycopg2.sql.SQL("SET search_path TO {}").format(
                    psycopg2.sql.Identifier(postgres_name(schema))))
    return conn


@contextmanager
def located(text: str, database: str | None, schema: str | None):
    """Find the table a Snowflake name names, as the session would.

    Args:
        text (str): the name, `[<database>.][<schema>.]<table>`.
        database (str | None): the session's database, for a name without
            one.
        schema (str | None): the session's schema, for a name without one.

    Yields:
        tuple: a cursor on the table's database, and the table's oid; None
            for a name Postgres reads and Snowflake does not.

    Raises:
        LookupError: the text is not a name, or nothing has it, with
            Postgres's message -- a text of Snowflake's this cannot check.
    """
    parts = object_name(text)
    conn = connect(parts[0] if parts and len(parts) == 3 else database, schema)
    try:
        with conn.cursor() as cur:
            try:
                if parts is None:
                    cur.execute("SELECT parse_ident(%s)", (text, ))
                else:
                    cur.execute("SELECT %s::regclass::oid", (".".join(
                        '"' + postgres_name(part).replace('"', '""') + '"'
                        for part in parts[-2:]), ))
            except psycopg2.Error as failure:
                raise LookupError(failure.diag.message_primary) from None
            yield cur, None if parts is None else cur.fetchone()[0]
    finally:
        conn.close()


def snowflake_type(shown: str, nullable: bool) -> tuple[str, dict[str, Any]]:
    """The Snowflake type a Postgres column was created as.

    Each is a type the TYPES rewrite, or Postgres's own aliases, arrive at
    from one Snowflake has; Snowflake's standard name for it, as GET_DDL
    writes it, and its properties, as SHOW COLUMNS gives them. Snowflake
    has one integer type, NUMBER(38,0), which is also what NUMBER alone
    means, and one string type, VARCHAR. A type Snowflake has no name for
    here keeps Postgres's.

    Args:
        shown (str): the column's type, as `format_type` spells it.
        nullable (bool): whether the column takes NULL.

    Returns:
        tuple[str, dict[str, Any]]: the name, and the `data_type` object.
    """
    if re.fullmatch(r"integer|bigint|smallint|numeric", shown):
        shown = "numeric(38,0)"
    found = re.fullmatch(r"numeric\((\d+),(\d+)\)", shown)
    if found:
        precision, scale = int(found[1]), int(found[2])
        return f"NUMBER({precision},{scale})", {
            "type": "FIXED",
            "precision": precision,
            "scale": scale,
            "nullable": nullable
        }
    found = re.fullmatch(r"(?:character varying|character)(?:\((\d+)\))?|text",
                         shown)
    if found:
        length = int(found[1] or MAX_VARCHAR)
        return f"VARCHAR({length})", {
            "type": "TEXT",
            "length": length,
            "byteLength": min(4 * length, MAX_VARCHAR),
            "nullable": nullable,
            "fixed": False
        }
    found = re.fullmatch(
        r"(timestamp|time)(?:\((\d)\))? (with|without) "
        r"time zone", shown)
    if found:
        name = ("TIME" if found[1] == "time" else
                "TIMESTAMP_NTZ" if found[3] == "without" else "TIMESTAMP_TZ")
        scale = int(found[2] or 9)
        return f"{name}({scale})", {
            "type": name,
            "precision": 0,
            "scale": scale,
            "nullable": nullable
        }
    name, kind = SCALAR_TYPES.get(shown, (shown.upper(), shown.upper()))
    return name, {"type": kind, "nullable": nullable}


def snowflake_default(expression: str | None) -> str | None:
    """A column default as Snowflake shows it.

    Args:
        expression (str | None): as `pg_get_expr` gives it.

    Returns:
        str | None: the Snowflake spelling, None for no default.
    """
    if expression is None:
        return None
    for pattern, replacement in DEFAULTS:
        expression = pattern.sub(replacement, expression)
    return expression


def columns(cur, oid: int, like: str = "%") -> list[tuple]:
    """A table's columns, in order.

    Args:
        cur: a cursor on the table's database.
        oid (int): the table.
        like (str): only the columns whose names match, case-insensitively.

    Returns:
        list[tuple]: name, type, NOT NULL, default, comment, and the
            identity's start and increment when it has one.
    """
    cur.execute(
        "SELECT a.attname, format_type(a.atttypid, a.atttypmod), "
        "a.attnotnull, pg_get_expr(d.adbin, d.adrelid), "
        "col_description(a.attrelid, a.attnum), s.seqstart, s.seqincrement "
        "FROM pg_attribute a LEFT JOIN pg_attrdef d "
        "ON d.adrelid = a.attrelid AND d.adnum = a.attnum "
        "LEFT JOIN pg_sequence s ON a.attidentity <> '' AND s.seqrelid = "
        "pg_get_serial_sequence(a.attrelid::regclass::text, a.attname)"
        "::regclass WHERE a.attrelid = %s AND a.attnum > 0 "
        "AND NOT a.attisdropped AND a.attname ILIKE %s ORDER BY a.attnum",
        (oid, like))
    return cur.fetchall()


def described(cur, oid: int) -> tuple[str, str, str, str | None, str]:
    """Where a table is, what it is called, and what kind it is.

    Args:
        cur: a cursor on the table's database.
        oid (int): the table.

    Returns:
        tuple: database, schema and name as Postgres has them, the
            table's comment, and its `relkind`.
    """
    cur.execute(
        "SELECT current_database(), n.nspname, c.relname, "
        "obj_description(c.oid, 'pg_class'), c.relkind FROM pg_class c "
        "JOIN pg_namespace n ON n.oid = c.relnamespace WHERE c.oid = %s",
        (oid, ))
    return cur.fetchone()


def table_ddl(cur, oid: int, qualified: bool) -> str | None:
    """What `GET_DDL('TABLE', ...)` answers for a table.

    The shape is Snowflake's: the standard type names, NOT NULL and
    DEFAULT inline, an identity as `autoincrement start ... increment ...
    noorder` (NOORDER being every new column's since the 2024_01 bundle),
    and the primary key, unique and foreign keys out of line and without
    the names Snowflake gave them. Constraints are listed in the order
    they were created. Postgres makes an identity column NOT NULL, which
    Snowflake does only for a key.

    Args:
        cur: a cursor on the table's database.
        oid (int): the table.
        qualified (bool): whether the table is named with its database
            and schema, as the third argument asks.

    Returns:
        str | None: the DDL; None for anything but a table.
    """
    database, schema, table, comment, kind = described(cur, oid)
    if kind not in ("r", "p"):
        return None
    lines = []
    for name, shown, not_null, default, note, start, step in columns(cur, oid):
        line = [
            identifier(snowflake_name(name)),
            snowflake_type(shown, not not_null)[0]
        ]
        if not_null:
            line.append("NOT NULL")
        if default is not None:
            line.append(f"DEFAULT {snowflake_default(default)}")
        if start is not None:
            line.append(f"autoincrement start {start} increment {step} "
                        "noorder")
        if note is not None:
            line.append(f"COMMENT {literal(note)}")
        lines.append(" ".join(line))
    cur.execute(
        "SELECT c.contype, ARRAY(SELECT a.attname::text FROM "
        "unnest(c.conkey) WITH ORDINALITY k(n, i) JOIN pg_attribute a "
        "ON a.attrelid = c.conrelid AND a.attnum = k.n ORDER BY k.i), "
        "fn.nspname, f.relname, ARRAY(SELECT a.attname::text FROM "
        "unnest(c.confkey) WITH ORDINALITY k(n, i) JOIN pg_attribute a "
        "ON a.attrelid = c.confrelid AND a.attnum = k.n ORDER BY k.i) "
        "FROM pg_constraint c LEFT JOIN pg_class f ON f.oid = c.confrelid "
        "LEFT JOIN pg_namespace fn ON fn.oid = f.relnamespace "
        "WHERE c.conrelid = %s AND c.contype IN ('p', 'u', 'f') "
        "ORDER BY c.oid", (oid, ))
    for kind, keys, other_schema, other, other_keys in cur.fetchall():
        keys = ", ".join(identifier(snowflake_name(key)) for key in keys)
        if kind == "f":
            target = ".".join(
                identifier(snowflake_name(part))
                for part in (catalog_name(database), other_schema, other))
            other_keys = ", ".join(
                identifier(snowflake_name(key)) for key in other_keys)
            lines.append(f"foreign key ({keys}) references "
                         f"{target}({other_keys})")
        else:
            lines.append(("primary key" if kind == "p" else "unique") +
                         f" ({keys})")
    name = ".".join(
        identifier(snowflake_name(part))
        for part in ((catalog_name(database), schema,
                      table) if qualified else (table, )))
    body = ",\n".join("\t" + line for line in lines)
    end = ");" if comment is None else f")COMMENT={literal(comment)}\n;"
    return f"create or replace TABLE {name} (\n{body}\n{end}"


def show_columns(name: str, like: str, database: str | None,
                 schema: str | None) -> list[dict[str, Any]] | None:
    """What `SHOW COLUMNS IN TABLE <name>` answers.

    Args:
        name (str): the table's name, as written.
        like (str): the LIKE pattern, `%` for none.
        database (str | None): the session's database.
        schema (str | None): the session's schema.

    Returns:
        list[dict[str, Any]] | None: as `column_rows`; None when the name
            is not one this reads.
    """
    with located(name, database, schema) as (cur, oid):
        return None if oid is None else column_rows(cur, oid, like)


def column_rows(cur, oid: int, like: str = "%") -> list[dict[str, Any]]:
    """SHOW COLUMNS's rows for one table.

    Args:
        cur: a cursor on the table's database.
        oid (int): the table.
        like (str): the LIKE pattern, `%` for none.

    Returns:
        list[dict[str, Any]]: a row per column, under SHOW's lower-case
            column names and in the order Snowflake's documentation lists
            them.
    """
    where, namespace, table = described(cur, oid)[:3]
    rows = []
    for name, shown, not_null, default, note, start, step in columns(
            cur, oid, like):
        data_type = snowflake_type(shown, not not_null)[1]
        identity = f"IDENTITY START {start} INCREMENT {step} NOORDER"
        rows.append({
            "table_name": snowflake_name(table),
            "schema_name": snowflake_name(namespace),
            "column_name": snowflake_name(name),
            "data_type": json.dumps(data_type, separators=(",", ":")),
            "null?": "false" if not_null else "true",
            "default": snowflake_default(default) or "",
            "kind": "COLUMN",
            "expression": "",
            "comment": note or "",
            "database_name": catalog_name(where),
            "autoincrement": "" if start is None else identity,
            "schema_evolution_record": None,
        })
    return rows


def session_values(sql: str, database: str | None,
                   schema: str | None) -> tuple[str, dict[str, str]]:
    """Answer the calls only the session can: its database and schema,
    and GET_DDL.

    Each becomes a one-row subquery whose column is named for the call,
    so an unaliased call keeps the label Snowflake gives it -- the call's
    text, in upper case. Postgres cuts a name at 63 bytes, so the name is
    a placeholder, swapped for the label once the rows are back. A context
    call compared with a catalog column is the name Postgres keeps
    instead, as `fold_catalog_literals` makes a literal.

    Args:
        sql (str): the Postgres spelling, after `rewrite`.
        database (str | None): the session's database.
        schema (str | None): the session's schema.

    Returns:
        tuple[str, dict[str, str]]: the SQL, and each placeholder's label.
    """
    labels = {}

    def labelled(value: str, call: str) -> str:
        """A subquery answering `value` under a placeholder name."""
        name = f"snowflake label {len(labels)}"
        labels[name] = call.upper()
        return f'(SELECT {value} AS "{name}")'

    code = bare_code(sql)
    for call in reversed(list(CONTEXT_CALL.finditer(code))):
        value = database if call[1].upper() == "DATABASE" else schema
        if CATALOG_COMPARED.search(code[:call.start()]) or \
                COMPARED_WITH_CATALOG.match(code, call.end()):
            kept = None if value is None else postgres_name(value)
            # SNOWFLAKE's catalog entry is the maintenance database's, as
            # `catalog_name` reads it the other way.
            if call[1].upper() == "DATABASE" and kept == ACCOUNT_METADATA_DB:
                kept = MAINTENANCE_DB
            text = "NULL" if kept is None else literal(kept)
        else:
            text = labelled("NULL::text" if value is None else literal(value),
                            sql[call.start():call.end()])
        sql = sql[:call.start()] + text + sql[call.end():]
    code = bare_code(sql)
    for found in reversed(
            list(re.finditer(rf"{START}GET_DDL\s*\(", code, re.IGNORECASE))):
        call = GET_DDL_CALL.match(sql, found.start())
        if not call:
            continue
        with located(call[2].replace("''", "'"), database,
                     schema) as (cur, oid):
            text = None if oid is None else table_ddl(
                cur, oid, (call[3] or "").upper() == "TRUE")
        if text is not None:
            sql = sql[:call.start()] + labelled(literal(text),
                                                call[0]) + sql[call.end():]
    return sql, labels


def _admin_execute(query: str) -> None:
    """Run a statement that Postgres refuses inside a transaction.

    Args:
        query (str): a `CREATE DATABASE` or `DROP DATABASE`.
    """
    guarded = CREATE_DB_IF_MISSING.match(query)
    conn = psycopg2.connect(database=MAINTENANCE_DB, **dsn_parts())
    conn.set_isolation_level(psycopg2.extensions.ISOLATION_LEVEL_AUTOCOMMIT)
    try:
        with conn.cursor() as cur:
            try:
                cur.execute(CREATE_DB_IF_MISSING.sub(r"\1", query))
            except psycopg2.errors.DuplicateDatabase:
                # What `IF NOT EXISTS` asked for. Without the guard the
                # caller wanted the error, so it is re-raised.
                if not guarded:
                    raise
    finally:
        conn.close()


def run(query: str,
        database: str | None = None,
        schema: str | None = None) -> tuple[list[dict[str, Any]], int]:
    """Run one statement and return its rows and its row count.

    Args:
        query (str): the SQL as the caller wrote it.
        database (str | None): the database to use when the query names
            none of its own.
        schema (str | None): the schema an unqualified name resolves in,
            as `used` resolved it; None leaves Postgres's own.

    Returns:
        tuple[list[dict[str, Any]], int]: the rows -- empty for a statement
            that returns none -- and the number of rows affected.

    Raises:
        ValueError: the call holds more than one statement.
    """
    count = statement_count(query)
    if count > 1:
        raise ValueError(MULTIPLE_STATEMENTS.format(count))
    if USE_STATEMENT.match(query):
        return [], 0
    if CREATE_DROP_DB.match(query):
        _admin_execute(query)
        return [], 0
    shown = SHOW_COLUMNS.match(query)
    if shown:
        like = (shown["like"] if shown["like"] is not None else "%").replace(
            "''", "'")
        rows = show_columns(shown["name"], like, database, schema)
        if rows is not None:
            return rows, len(rows)

    sql, labels = session_values(rewrite(query, schema), database, schema)
    conn = connect(database_in(query) or database, schema)
    try:
        with conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
            cur.execute(sql)
            if cur.description is None:
                return [], cur.rowcount
            return present([{
                labels.get(name, name): value
                for name, value in row.items()
            }
                            for row in cur.fetchall()],
                           reads_catalog(query, schema)), cur.rowcount
    finally:
        conn.close()


def execute(query: str,
            database: str | None = None,
            schema: str | None = None) -> list[dict[str, Any]]:
    """Run one statement and return its rows.

    Args:
        query (str): the SQL as the caller wrote it.
        database (str | None): the database to use when the query names
            none of its own.
        schema (str | None): the schema an unqualified name resolves in.

    Returns:
        list[dict[str, Any]]: the rows, empty for a statement that returns
            none.
    """
    return run(query, database, schema)[0]
